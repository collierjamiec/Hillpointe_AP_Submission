"""Builds runs/RERUN_EVIDENCE.md from the real run outputs, so the evidence cannot drift from what actually happened."""
import csv
import json
from collections import Counter, defaultdict
from pathlib import Path

LABELS = {
    "run1_batch01": "Run 1: Batch 01, first time",
    "run2_batch01_RERUN": "Run 2: Batch 01 again (exact same files)",
    "run3_batch02": "Run 3: Batch 02 (resends, reprints, a revised invoice and one new bill)",
    "run4_batch02_RERUN": "Run 4: Batch 02 again (exact same files)",
}


def build(out_dir: Path, state_dir: Path):
    out_dir, state_dir = Path(out_dir), Path(state_dir)
    runs = [r for r in LABELS if (out_dir / r / "decisions.json").exists()]
    L = ["# Rerun evidence", "",
         "Generated by `python -m ap_workflow demo`. Every number below is read from the files each run wrote.", ""]
    L += ["## 1. What each run did", "", "| Run | Documents | Entered (Intacct) | Entered (Entrata) | Held | Duplicate | Skipped (same file, already entered) | Rows written to import file |",
          "|---|---|---|---|---|---|---|---|"]
    seen = defaultdict(list)
    for r in runs:
        decs = json.loads((out_dir / r / "decisions.json").read_text())
        c = Counter(d["decision"] for d in decs)
        rows = list(csv.DictReader(open(out_dir / r / "intacct_bill_import.csv", encoding="utf-8")))
        for row in rows:
            seen[(row["VENDOR_ID"], row["BILL_NO"])].append(r)
        L.append(f"| {LABELS[r]} | {len(decs)} | {c.get('ENTER_INTACCT', 0)} | {c.get('ENTER_ENTRATA', 0)} | {c.get('HOLD', 0)} | {c.get('DUP', 0)} | {c.get('SKIP_ALREADY_ENTERED', 0)} | {len(rows)} |")
    L += ["", "## 2. Proof that nothing is entered twice", ""]
    per_bill = defaultdict(set)
    for (v, b), rs in seen.items():
        per_bill[(v, b)] |= set(rs)
    multi = {k: sorted(v) for k, v in per_bill.items() if len(v) > 1}
    L.append(f"Bills written to any import file across all runs: **{len(per_bill)}** unique vendor and bill number pairs.")
    L.append(f"Pairs that appear in more than one run's import file: **{len(multi)}**.")
    if multi:
        for k, v in multi.items():
            L.append(f"- FAIL {k} appears in {v}")
    else:
        L.append("")
        L.append("Result: PASS. Every bill appears in exactly one import file, once.")
    L += ["", "| Vendor | Bill No | Written in |", "|---|---|---|"]
    for (v, b), rs in sorted(per_bill.items()):
        L.append(f"| {v} | {b} | {', '.join(sorted(rs))} |")

    L += ["", "## 3. Batch 02 in detail", ""]
    if "run3_batch02" in runs:
        decs = json.loads((out_dir / "run3_batch02" / "decisions.json").read_text())
        L += ["| File | Invoice | Result | What happened |", "|---|---|---|---|"]
        for d in decs:
            what = (d["reasons"][0] if d["reasons"] else ("Entered. " + (d["info"][0] if d["info"] else ""))).replace("|", "/")
            L.append(f"| {d['file']} | {d['bill_no']} | {d['decision']} | {what[:260]} |")
    L += ["", "## 4. How the duplicate logic works", "",
          "1. **Find the vendor first.** The duplicate key always starts with the vendor ID, so the same invoice number from two different vendors never collides (Copperline 55102 versus Bluewater BOP-55102, or Copperline 55388 versus Live Oak 55388).",
          "2. **Clean the invoice number.** Upper case, drop a leading INV or INVOICE label, drop dashes and spaces, drop leading zeros. So `INV-20417`, `inv 020417` and `20417` become the same key.",
          "3. **Look in three places:** the ERP history for Intacct and Entrata, the register of bills this workflow already entered, and the register of bills it held.",
          "4. **Decide:**",
          "   * Found in ERP history, or entered by an earlier run from a different file: **DUP**, route to the AP Manager. A watermark such as REPRINT or PAST DUE is mentioned in the reason but is not needed to catch it.",
          "   * Entered by an earlier run from the same inbox file: **skipped**, nothing to do. This is what a rerun of the same batch looks like.",
          "   * Previously **held**: not a duplicate. A corrected or revised version is checked again from the start, because a held document was never entered.",
          "   * Same vendor and same amount with a different invoice number: **not** a duplicate. Recurring services bill the same amount every month (Coastal CSS-88301 and CSS-88611).",
          "5. **Revised invoices.** If the original was already entered, the revision is a DUP and goes to the AP Manager. If the original was only held (HPA-31877), the revision is entered and the held original is closed out in the register.",
          "6. **Credits first.** Credit memos are processed before invoices so PO balances are correct when the invoices are tested.", "",
          "## 5. Where the record of processed invoices lives", "",
          f"`{state_dir.name}/processed_register.csv` holds one row per bill key with its status (ENTERED, HELD or SUPERSEDED), vendor, amount, source file, SHA-256 of the file and the run that entered it. "
          f"`{state_dir.name}/run_log.csv` is an append-only log with one row per document per run. Both are plain CSV, so they can be opened in Excel, diffed in git and copied to another computer. "
          "A run only saves the register after the Intacct pre-flight check passes, so a failed run cannot leave half-written state behind.", "",
          "## 6. Register after all runs", "", "| Status | Key | Source file | Amount | Run | Note |", "|---|---|---|---|---|---|"]
    with open(state_dir / "processed_register.csv", newline="", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            L.append(f"| {r['status']} | {r['key']} | {r['source_file']} | {r['amount']} | {r['first_run']} | {r['note'][:110]} |")
    (out_dir / "RERUN_EVIDENCE.md").write_text("\n".join(L) + "\n", encoding="utf-8")
